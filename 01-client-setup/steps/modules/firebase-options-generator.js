const fs = require('fs');
const path = require('path');

/**
 * Extract iOS config from GoogleService-Info.plist
 * @param {string} plistPath - Path to GoogleService-Info.plist
 * @returns {object|null} iOS Firebase config or null if not found
 */
function extractiOSConfig(plistPath) {
  if (!fs.existsSync(plistPath)) {
    return null;
  }

  const content = fs.readFileSync(plistPath, 'utf8');

  const getValue = (key) => {
    const regex = new RegExp(`<key>${key}</key>\\s*<string>([^<]+)</string>`);
    const match = content.match(regex);
    return match ? match[1] : null;
  };

  const apiKey = getValue('API_KEY');
  const appId = getValue('GOOGLE_APP_ID');
  const messagingSenderId = getValue('GCM_SENDER_ID');
  const projectId = getValue('PROJECT_ID');
  const storageBucket = getValue('STORAGE_BUCKET');
  const iosClientId = getValue('CLIENT_ID');
  const iosBundleId = getValue('BUNDLE_ID');

  if (!apiKey || !appId || !projectId) {
    return null;
  }

  return {
    apiKey,
    appId,
    messagingSenderId,
    projectId,
    storageBucket,
    iosClientId,
    iosBundleId,
  };
}

/**
 * Extract Android config from google-services.json
 * @param {string} jsonPath - Path to google-services.json
 * @param {string} bundleId - Expected bundle/package ID
 * @returns {object|null} Android Firebase config or null if not found
 */
function extractAndroidConfig(jsonPath, bundleId) {
  if (!fs.existsSync(jsonPath)) {
    return null;
  }

  try {
    const content = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
    const projectInfo = content.project_info || {};

    const client = content.client?.find(
      (c) => c.client_info?.android_client_info?.package_name === bundleId
    );

    if (!client) {
      console.log(`  ⚠️  No Android client found for package: ${bundleId}`);
      const firstClient = content.client?.[0];
      if (firstClient) {
        console.log(
          `  ℹ️  Using first available client: ${firstClient.client_info?.android_client_info?.package_name}`
        );
        return extractClientConfig(firstClient, projectInfo);
      }
      return null;
    }

    return extractClientConfig(client, projectInfo);
  } catch {
    return null;
  }
}

/**
 * Extract config from a client entry
 */
function extractClientConfig(client, projectInfo) {
  const apiKey = client.api_key?.[0]?.current_key;
  const appId = client.client_info?.mobilesdk_app_id;

  if (!apiKey || !appId) {
    return null;
  }

  return {
    apiKey,
    appId,
    messagingSenderId: projectInfo.project_number,
    projectId: projectInfo.project_id,
    storageBucket: projectInfo.storage_bucket,
  };
}

/**
 * Generate firebase_options.dart content
 * @param {object} androidConfig - Android Firebase config
 * @param {object} iosConfig - iOS Firebase config
 * @param {string} clientName - Client name for comment
 * @returns {string} Generated Dart code
 */
function generateFirebaseOptionsContent(androidConfig, iosConfig, clientName) {
  return `// File generated based on google-services.json and GoogleService-Info.plist
// for client: ${clientName}
// Generated by loyalty-composer firebase-options-generator
// ignore_for_file: type=lint
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart'
    show defaultTargetPlatform, kIsWeb, TargetPlatform;

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) {
      throw UnsupportedError(
        'DefaultFirebaseOptions have not been configured for web - '
        'you can reconfigure this by running the FlutterFire CLI again.',
      );
    }
    switch (defaultTargetPlatform) {
      case TargetPlatform.android:
        return android;
      case TargetPlatform.iOS:
        return ios;
      case TargetPlatform.macOS:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for macos - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      case TargetPlatform.windows:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for windows - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      case TargetPlatform.linux:
        throw UnsupportedError(
          'DefaultFirebaseOptions have not been configured for linux - '
          'you can reconfigure this by running the FlutterFire CLI again.',
        );
      default:
        throw UnsupportedError(
          'DefaultFirebaseOptions are not supported for this platform.',
        );
    }
  }

  static const FirebaseOptions android = FirebaseOptions(
    apiKey: '${androidConfig.apiKey}',
    appId: '${androidConfig.appId}',
    messagingSenderId: '${androidConfig.messagingSenderId}',
    projectId: '${androidConfig.projectId}',
    storageBucket: '${androidConfig.storageBucket}',
  );

  static const FirebaseOptions ios = FirebaseOptions(
    apiKey: '${iosConfig.apiKey}',
    appId: '${iosConfig.appId}',
    messagingSenderId: '${iosConfig.messagingSenderId}',
    projectId: '${iosConfig.projectId}',
    storageBucket: '${iosConfig.storageBucket}',
    iosClientId: '${iosConfig.iosClientId}',
    iosBundleId: '${iosConfig.iosBundleId}',
  );
}
`;
}

/**
 * Generate firebase_options.dart from existing config files
 * @param {string} clientDir - Client directory path
 * @param {string} targetRoot - Target white_label_app root path
 * @param {string} bundleId - Expected bundle/package ID
 * @param {string} clientName - Client name for comments
 * @returns {boolean} True if generation succeeded
 */
function generateFirebaseOptionsFromConfigs(clientDir, targetRoot, bundleId, clientName) {
  console.log('  🔧 Generating firebase_options.dart from existing config files...');

  const androidJsonPath = path.join(targetRoot, 'android', 'app', 'google-services.json');
  const iosPlistPath = path.join(targetRoot, 'ios', 'Runner', 'GoogleService-Info.plist');

  const androidConfig = extractAndroidConfig(androidJsonPath, bundleId);
  const iosConfig = extractiOSConfig(iosPlistPath);

  if (!androidConfig) {
    console.log('  ❌ Could not extract Android config from google-services.json');
    return false;
  }

  if (!iosConfig) {
    console.log('  ❌ Could not extract iOS config from GoogleService-Info.plist');
    return false;
  }

  const content = generateFirebaseOptionsContent(androidConfig, iosConfig, clientName);

  const dartDest = path.join(targetRoot, 'lib', 'firebase_options.dart');
  fs.writeFileSync(dartDest, content, 'utf8');
  console.log('  ✅ firebase_options.dart gerado a partir dos arquivos de configuração');

  const clientLibDir = path.join(clientDir, 'lib');
  if (!fs.existsSync(clientLibDir)) {
    fs.mkdirSync(clientLibDir, { recursive: true });
  }
  fs.copyFileSync(dartDest, path.join(clientLibDir, 'firebase_options.dart'));
  console.log('  ✅ firebase_options.dart salvo na pasta do cliente para uso futuro');

  return true;
}

module.exports = {
  extractAndroidConfig,
  extractiOSConfig,
  generateFirebaseOptionsContent,
  generateFirebaseOptionsFromConfigs,
};
